CREATE OR ALTER PROCEDURE dbo.spConfig_GridLogFileEnd
     (@file_id INT)
AS
BEGIN

--*************************************************************************************************
-- If beginning the log then add the file and get the ID
--*************************************************************************************************
UPDATE [grid].[File]
   SET EndDate			= GETDATE()
 WHERE FileID			= @file_id

END
GO